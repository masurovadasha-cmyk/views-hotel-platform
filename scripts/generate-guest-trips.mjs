import {readFileSync,writeFileSync} from 'node:fs';
const doc=JSON.parse(readFileSync(new URL('../contracts/guest-trips.openapi.json',import.meta.url),'utf8'));
// Deliberately scoped to the read-only guest trips contract; unsupported shapes fail.
function type(s){
 let t;
 if(s.$ref)t=s.$ref.split('/').at(-1);
 else if(s.type==='string')t='string';
 else if(s.type==='array')t=`Array<${type(s.items)}>`;
 else if(s.type==='object')t=s.additionalProperties?`Record<string,${type(s.additionalProperties)}>`:
  `{${Object.entries(s.properties).map(([k,v])=>`${JSON.stringify(k)}${s.required?.includes(k)?'':'?'}:${type(v)}`).join(';')}}`;
 else throw Error('Unsupported schema');
 return t+(s.nullable?'|null':'');
}
let output='// Generated by scripts/generate-guest-trips.mjs. Do not edit.\n';
for(const [name,schema] of Object.entries(doc.components.schemas))output+=`export type ${name}=${type(schema)};\n`;
output+='export function createGuestTripsClient(request:(route:string)=>Promise<unknown>){return {\n';
for(const [path,methods] of Object.entries(doc.paths)){
 if(Object.keys(methods).join()!=='get')throw Error('Only GET supported');
 const op=methods.get,[p]=op.parameters;
 if(op.parameters.length!==1||!['query','path'].includes(p.in))throw Error('Unsupported parameters');
 const route=p.in==='path'?JSON.stringify(path.slice(1).split('{')[0])+`+encodeURIComponent(${p.name})`:
  JSON.stringify(path.slice(1))+`+(${p.name}!==undefined?'?${p.name}='+encodeURIComponent(${p.name}):'')`;
 output+=`${op.operationId}:(${p.name}${p.required?'':'?'}:string)=>request(${route}) as Promise<${type(op.responses['200'].content['application/json'].schema)}>,\n`;
}
output+='};}\n';
const target=new URL('../src/api/guest-trips.generated.ts',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw Error('Generated guest trips client is stale');}
else writeFileSync(target,output);
